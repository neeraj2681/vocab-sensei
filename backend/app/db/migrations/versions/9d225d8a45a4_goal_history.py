def _history(created_at, goal, previous, since):
    """The goal changes the old columns imply, oldest first; none if the goal never changed."""
    if since is None:
        return []
    earlier = previous if previous is not None else goal
    rows = []
    if created_at < GOALS_SHIPPED and earlier != FIRST_GOAL:
        # A later change overwrote what the first days had; they were judged by 10.
        rows += [(FIRST_GOAL, created_at), (earlier, GOALS_SHIPPED)]
    else:
        rows.append((earlier, min(created_at, since)))
    rows.append((goal, since))
    return rows


